-- Published matchup groups: one of your teams against many opponents, posted
-- publicly under a short slug.
--
-- A published row is a SNAPSHOT. `document` is the exact string `encodeGroup`
-- produced at publish time, stored verbatim as text rather than jsonb so no
-- key reordering or number normalisation can touch it. It changes only when
-- its author publishes again, so a link posted on X cannot shift under its
-- readers.
--
-- NOTE ON ENUMERATION: an earlier design called for reads through a
-- `security definer` function taking the slug, to stop anyone listing every
-- shared plan. The forum reverses that — a feed exists precisely to enumerate
-- these — so SELECT is simply public. They are public posts.

create table if not exists public.published_groups (
  -- Short, URL-safe, generated by the client and retried on collision.
  slug text primary key
    constraint published_slug_shape check (slug ~ '^[a-z0-9]{6,12}$'),
  user_id uuid not null default auth.uid()
    references auth.users (id) on delete cascade,
  title text not null
    constraint published_title_len check (char_length(title) between 1 and 120),
  -- The author's prose above the matchups. Optional, capped so a post stays a
  -- post rather than becoming a hosting service.
  description text not null default ''
    constraint published_description_len check (char_length(description) <= 4000),
  -- Verbatim `encodeGroup` output. Carries my team, every opponent, and the
  -- plan for each.
  document text not null
    constraint published_document_len check (char_length(document) <= 400000),
  -- Denormalised for the feed card, so listing never parses the document.
  team_name text not null,
  regulation text not null,
  species text[] not null,
  opponent_count integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists published_groups_recent
  on public.published_groups (created_at desc);
create index if not exists published_groups_author
  on public.published_groups (user_id, created_at desc);

alter table public.published_groups enable row level security;

create policy "published groups are world-readable"
  on public.published_groups for select
  using (true);

create policy "published groups are author-insertable"
  on public.published_groups for insert
  with check ((select auth.uid()) = user_id);

create policy "published groups are author-updatable"
  on public.published_groups for update
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

create policy "published groups are author-deletable"
  on public.published_groups for delete
  using ((select auth.uid()) = user_id);
